const currentLanguage = localStorage.getItem("wanderly-language") || "ru";
function applyLanguage(language) {
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = translations[language][element.dataset.i18n];
    if (value) element.innerHTML = value;
  });
  document.querySelectorAll("[data-lang-toggle]").forEach((button) => {
    button.textContent =
      language === "ru" ? "EN" : language === "en" ? "UZ" : "RU";
  });
  localStorage.setItem("wanderly-language", language);
}
applyLanguage(currentLanguage);

document
  .querySelectorAll("[data-lang-toggle]")
  .forEach((button) =>
    button.addEventListener("click", () =>
      applyLanguage(
        document.documentElement.lang === "ru"
          ? "en"
          : document.documentElement.lang === "en"
            ? "uz"
            : "ru",
      ),
    ),
  );
document
  .querySelector(".menu-toggle")
  ?.addEventListener("click", () =>
    document.querySelector(".main-nav").classList.toggle("open"),
  );

const observer = new IntersectionObserver(
  (entries) =>
    entries.forEach((entry) => {
      if (entry.isIntersecting) entry.target.classList.add("visible");
    }),
  { threshold: 0.12 },
);
document
  .querySelectorAll(".reveal")
  .forEach((element) => observer.observe(element));

document
  .querySelectorAll(".trip-card, .destination-row, .team-card, .journal-small")
  .forEach((element, index) => {
    element.style.transitionDelay = `${(index % 3) * 90}ms`;
  });

document.querySelectorAll(".inline-form, .contact-form").forEach((form) =>
  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const status = form.querySelector(".form-status");
    if (status) {
      status.textContent =
        document.documentElement.lang === "ru"
          ? "Готово! Проверьте почту."
          : document.documentElement.lang === "en"
            ? "Done! Check your inbox."
            : "Tayyor! Pochtangizni tekshiring.";
      form.reset();
    }
  }),
);

document.querySelectorAll(".filter").forEach((button) =>
  button.addEventListener("click", () => {
    document
      .querySelectorAll(".filter")
      .forEach((item) => item.classList.remove("active"));
    button.classList.add("active");
    const filter = button.dataset.filter;
    document.querySelectorAll(".destination-row").forEach((row) => {
      row.hidden = filter !== "all" && row.dataset.category !== filter;
    });
  }),
);
